package com.queryexe.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Collections;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import com.queryexe.model.data.QueryData;

class ChangeApplierTest {

    private Connection connection;

    @BeforeEach
    void openH2() throws SQLException {
        connection = DriverManager.getConnection("jdbc:h2:mem:applier;DB_CLOSE_DELAY=-1", "sa", "");
        try (Statement s = connection.createStatement()) {
            s.execute("DROP ALL OBJECTS");
            s.execute("CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, V VARCHAR(10))");
            s.execute("INSERT INTO T(V) VALUES ('one')");
        }
    }

    @AfterEach
    void close() throws SQLException {
        connection.close();
    }

    private static Set<QueryData> identitySet(QueryData... queries) {
        Set<QueryData> set = Collections.newSetFromMap(new IdentityHashMap<>());
        set.addAll(List.of(queries));
        return set;
    }

    private String scalar(String sql) throws SQLException {
        try (Statement s = connection.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            return rs.next() ? rs.getString(1) : null;
        }
    }

    @Test
    void commitsAllStatements() throws SQLException {
        QueryData update = new QueryData("UPDATE T SET V = ? WHERE ID = ?", List.of("changed", 1));
        QueryData insert = new QueryData("INSERT INTO T(V) VALUES (?)", List.of("two"));

        ChangeApplier.apply(connection, List.of(update, insert), identitySet(insert));

        assertEquals("changed", scalar("SELECT V FROM T WHERE ID = 1"));
        assertEquals("2", scalar("SELECT COUNT(*) FROM T"));
    }

    @Test
    void reportsGeneratedKeysOnlyForInserts() throws SQLException {
        QueryData update = new QueryData("UPDATE T SET V = ? WHERE ID = ?", List.of("x", 1));
        QueryData insert = new QueryData("INSERT INTO T(V) VALUES (?)", List.of("two"));

        Map<QueryData, Map<String, Object>> keys =
                ChangeApplier.apply(connection, List.of(update, insert), identitySet(insert));

        assertFalse(keys.containsKey(update));
        Map<String, Object> insertKeys = keys.get(insert);
        assertNotNull(insertKeys);
        assertEquals(2, ((Number) insertKeys.get("ID")).intValue());
    }

    @Test
    void rollsBackEverythingWhenOneStatementFails() throws SQLException {
        QueryData good = new QueryData("UPDATE T SET V = ? WHERE ID = ?", List.of("changed", 1));
        QueryData duplicateKey = new QueryData("INSERT INTO T(ID, V) VALUES (?, ?)", List.of(1, "dup"));

        assertThrows(SQLException.class,
                () -> ChangeApplier.apply(connection, List.of(good, duplicateKey), identitySet(duplicateKey)));

        assertEquals("one", scalar("SELECT V FROM T WHERE ID = 1"));
        assertEquals("1", scalar("SELECT COUNT(*) FROM T"));
        assertTrue(connection.getAutoCommit(), "autocommit must be restored after a failure");
    }

    @Test
    void restoresAPreviousNonAutocommitMode() throws SQLException {
        connection.setAutoCommit(false);
        QueryData update = new QueryData("UPDATE T SET V = ? WHERE ID = ?", List.of("kept", 1));

        ChangeApplier.apply(connection, List.of(update), identitySet());

        assertFalse(connection.getAutoCommit());
        connection.rollback(); // nothing pending: the apply already committed its own transaction
        assertEquals("kept", scalar("SELECT V FROM T WHERE ID = 1"));
    }

    @Test
    void nullParametersAreBoundAsNull() throws SQLException {
        QueryData update = new QueryData("UPDATE T SET V = ? WHERE ID = ?", java.util.Arrays.asList(null, 1));

        ChangeApplier.apply(connection, List.of(update), identitySet());

        assertEquals(null, scalar("SELECT V FROM T WHERE ID = 1"));
    }

    @Test
    void sqliteReportsItsRowidAsGeneratedKey(@TempDir Path dir) throws SQLException {
        try (Connection lite = DriverManager.getConnection("jdbc:sqlite:" + dir.resolve("t.db"))) {
            try (Statement s = lite.createStatement()) {
                s.execute("CREATE TABLE t(id INTEGER PRIMARY KEY AUTOINCREMENT, v TEXT)");
            }
            QueryData insert = new QueryData("INSERT INTO t(v) VALUES (?)", List.of("a"));

            Map<QueryData, Map<String, Object>> keys =
                    ChangeApplier.apply(lite, List.of(insert), identitySet(insert));

            Map<String, Object> insertKeys = keys.get(insert);
            assertEquals(1, insertKeys.size());
            assertEquals(1, ((Number) insertKeys.values().iterator().next()).intValue());
        }
    }
}
