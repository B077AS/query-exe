package com.queryexe.grid;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import com.queryexe.model.connections.ConnectionObject;
import com.queryexe.model.connections.H2Connection;
import com.queryexe.model.connections.SQLiteConnection;
import com.queryexe.service.DatabaseConnection;

/**
 * Edits made in a result grid must become correctly targeted, correctly quoted statements. These tests run the real
 * engines (H2 in memory, SQLite in a temp folder) through {@link GridModel}, without any UI.
 */
class GridModelTest {

    private Connection connection;
    private ConnectionObject object;
    private String connectionId;
    private int gridCounter;

    private void connect(ConnectionObject connectionObject) throws SQLException {
        object = connectionObject;
        connectionId = connectionObject.getId();
        DatabaseConnection.getInstance().initialize(connectionObject);
        connection = DatabaseConnection.getInstance().getConnection();
    }

    @AfterEach
    void disconnect() {
        if (connectionId != null) {
            DatabaseConnection.getInstance().close(connectionId);
            connectionId = null;
        }
    }

    private GridModel grid(String sql) throws SQLException {
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.execute();
            return new GridModel("g" + gridCounter++, ps, 1, 0, object);
        }
    }

    private void execute(String... statements) throws SQLException {
        try (Statement s = connection.createStatement()) {
            for (String statement : statements) {
                s.execute(statement);
            }
        }
    }

    private String scalar(String sql) throws SQLException {
        try (Statement s = connection.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            return rs.next() ? rs.getString(1) : null;
        }
    }

    private static int rowId(GridModel grid, int index) {
        return grid.snapshot().getRows().get(index).getId();
    }

    private static String text(GridModel grid, int row, int column) {
        return grid.snapshot().getRows().get(row).getC()[column];
    }

    private static void edit(GridModel grid, int row, int column, String value) {
        grid.edit(rowId(grid, row), column, value);
    }

    @Nested
    class OnH2 {

        @BeforeEach
        void fixture() throws SQLException {
            connect(new H2Connection("h2-edit", "h2", "H2", "jdbc:h2:mem:gridedit;DB_CLOSE_DELAY=-1", "sa", "", null));
            execute("DROP ALL OBJECTS",
                    "CREATE SCHEMA OTHER",
                    "CREATE TABLE PUBLIC.DUP(ID INT PRIMARY KEY, V VARCHAR(10))",
                    "CREATE TABLE OTHER.DUP(ID INT PRIMARY KEY, V VARCHAR(10))",
                    "INSERT INTO PUBLIC.DUP VALUES (1,'public'),(2,'p2')",
                    "INSERT INTO OTHER.DUP VALUES (1,'other'),(2,'o2')",
                    "CREATE TABLE PUBLIC.\"lower case\"(\"Id\" INT PRIMARY KEY, \"weird col\" VARCHAR(10))",
                    "INSERT INTO PUBLIC.\"lower case\" VALUES (1,'x')",
                    "CREATE TABLE PUBLIC.CK(B INT, A INT, TXT VARCHAR(10), PRIMARY KEY(B,A))",
                    "INSERT INTO PUBLIC.CK VALUES (1,2,'t'),(1,3,'u')",
                    "CREATE TABLE PUBLIC.IDENT(ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(10), CREATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        }

        @Test
        void editTargetsTheSchemaTheRowsCameFrom() throws Exception {
            GridModel grid = grid("SELECT * FROM OTHER.DUP ORDER BY ID");
            assertTrue(grid.snapshot().isEditable());

            edit(grid, 0, 1, "EDITED");
            assertEquals(List.of("UPDATE \"OTHER\".\"DUP\" SET \"V\" = ? WHERE \"ID\" = ?"), grid.pendingSql());
            grid.apply(connection);

            assertEquals("EDITED", scalar("SELECT V FROM OTHER.DUP WHERE ID = 1"));
            assertEquals("public", scalar("SELECT V FROM PUBLIC.DUP WHERE ID = 1"));
        }

        @Test
        void quotedMixedCaseAndSpacedNamesWork() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.\"lower case\"");
            edit(grid, 0, 1, "y");
            grid.apply(connection);
            assertEquals("y", scalar("SELECT \"weird col\" FROM PUBLIC.\"lower case\""));

            int added = grid.addRow().getFocusRow();
            grid.edit(added, 0, "2");
            grid.apply(connection);
            assertEquals("2", scalar("SELECT COUNT(*) FROM PUBLIC.\"lower case\""));
        }

        @Test
        void newRowOmitsUntouchedColumnsSoIdentityAndDefaultsApply() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.IDENT");
            int added = grid.addRow().getFocusRow();
            grid.edit(added, 1, "zzz");

            assertEquals(List.of("INSERT INTO \"PUBLIC\".\"IDENT\" (\"NAME\") VALUES (?)"), grid.pendingSql());
            grid.apply(connection);

            assertEquals("zzz", scalar("SELECT NAME FROM PUBLIC.IDENT"));
            assertNotNull(scalar("SELECT CREATED FROM PUBLIC.IDENT"));
        }

        @Test
        void aRowInsertedFromTheGridShowsTheValuesTheDatabaseDefaulted() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.IDENT");
            int added = grid.addRow().getFocusRow();
            grid.edit(added, 1, "zzz");
            grid.apply(connection);

            String created = text(grid, 0, 2);
            assertNotNull(created, "CREATED is filled in by the database, not left empty");
            assertFalse(created.isEmpty());
            assertEquals(scalar("SELECT CREATED FROM PUBLIC.IDENT"), created);
        }

        @Test
        void revertRestoresEditedAndDeletedRowsAndDropsNewOnes() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.DUP ORDER BY ID");
            edit(grid, 0, 1, "changed");
            grid.deleteRows(List.of(rowId(grid, 1)));
            grid.addRow();

            GridModel.Snapshot back = grid.revert();

            assertEquals(2, back.getRows().size());
            assertEquals("public", back.getRows().get(0).getC()[1]);
            assertEquals("p2", back.getRows().get(1).getC()[1]);
            assertFalse(grid.hasPendingChanges());
        }

        @Test
        void aRowInsertedFromTheGridCanBeEditedAfterwards() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.IDENT");
            int added = grid.addRow().getFocusRow();
            grid.edit(added, 1, "first");
            grid.apply(connection);

            assertNotNull(text(grid, 0, 0), "generated key must be filled in");
            assertFalse(grid.snapshot().getRows().get(0).isAdded());

            grid.edit(added, 1, "second");
            assertTrue(grid.pendingSql().get(0).startsWith("UPDATE"));
            grid.apply(connection);

            assertEquals("second", scalar("SELECT NAME FROM PUBLIC.IDENT"));
            assertEquals("1", scalar("SELECT COUNT(*) FROM PUBLIC.IDENT"));
        }

        @Test
        void editingTheKeyThenOtherCellsMakesOneUpdateWithTheOriginalKey() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.DUP ORDER BY ID");
            edit(grid, 1, 0, "20");
            edit(grid, 1, 1, "v20");
            edit(grid, 1, 0, "21");

            assertEquals(1, grid.pendingSql().size());
            grid.apply(connection);
            assertEquals("v20", scalar("SELECT V FROM PUBLIC.DUP WHERE ID = 21"));
            assertEquals("0", scalar("SELECT COUNT(*) FROM PUBLIC.DUP WHERE ID IN (2, 20)"));
        }

        @Test
        void deletingAnEditedRowDeletesByItsDatabaseKeyAndDropsTheUpdate() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.DUP ORDER BY ID");
            edit(grid, 0, 0, "100");
            grid.deleteRows(List.of(rowId(grid, 0)));

            assertEquals(1, grid.pendingSql().size());
            assertTrue(grid.pendingSql().get(0).startsWith("DELETE"));
            grid.apply(connection);
            assertEquals("0", scalar("SELECT COUNT(*) FROM PUBLIC.DUP WHERE ID = 1"));
            assertEquals("1", scalar("SELECT COUNT(*) FROM PUBLIC.DUP"));
        }

        @Test
        void compositeKeysMatchEveryKeyColumn() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.CK ORDER BY A");
            edit(grid, 1, 2, "UU");
            grid.apply(connection);
            assertEquals("UU", scalar("SELECT TXT FROM PUBLIC.CK WHERE A = 3"));
            assertEquals("t", scalar("SELECT TXT FROM PUBLIC.CK WHERE A = 2"));
        }

        @Test
        void joinsAndKeylessResultsStayReadOnly() throws Exception {
            GridModel join = grid("SELECT d.ID, o.ID FROM PUBLIC.DUP d JOIN OTHER.DUP o ON d.ID = o.ID");
            assertFalse(join.snapshot().isEditable());
            assertThrows(IllegalStateException.class, () -> join.edit(rowId(join, 0), 0, "9"));
            assertFalse(grid("SELECT 1 AS ONE").snapshot().isEditable());
        }

        @Test
        void aValueOfTheWrongTypeIsRefusedAndChangesNothing() throws Exception {
            GridModel grid = grid("SELECT * FROM PUBLIC.DUP ORDER BY ID");
            assertThrows(IllegalArgumentException.class, () -> edit(grid, 0, 0, "not a number"));
            assertFalse(grid.hasPendingChanges());
            assertEquals("1", text(grid, 0, 0));
        }

        @Test
        void aRowCanBeScriptedAsAnInsert() throws Exception {
            GridModel grid = grid("SELECT * FROM OTHER.DUP ORDER BY ID");
            String script = grid.rowInsertScript(rowId(grid, 0));
            assertTrue(script.startsWith("INSERT INTO \"OTHER\".\"DUP\""), script);
            assertTrue(script.contains("'other'"), script);
        }
    }

    @Nested
    class OnSqlite {

        @TempDir
        Path dir;

        @BeforeEach
        void fixture() throws SQLException {
            connect(new SQLiteConnection("lite-edit", "lite", "SQLite", "jdbc:sqlite:" + dir.resolve("main.db"), "", "", null));
            execute("ATTACH DATABASE '" + dir.resolve("aux.db").toString().replace("\\", "/") + "' AS aux",
                    "CREATE TABLE shared(id INTEGER PRIMARY KEY, v TEXT)",
                    "CREATE TABLE aux.shared(id INTEGER PRIMARY KEY, v TEXT)",
                    "CREATE TABLE \"my table\"(\"Id\" INTEGER PRIMARY KEY, \"weird col\" TEXT)",
                    "CREATE TABLE \"order\"(id INTEGER PRIMARY KEY AUTOINCREMENT, \"group\" TEXT)",
                    "INSERT INTO shared VALUES (1,'main')",
                    "INSERT INTO aux.shared VALUES (1,'aux')",
                    "INSERT INTO \"my table\" VALUES (1,'w')",
                    "INSERT INTO \"order\"(\"group\") VALUES ('g')");
        }

        @Test
        void aTableNameInSeveralAttachedDatabasesIsReadOnly() throws Exception {
            assertFalse(grid("SELECT * FROM aux.shared").snapshot().isEditable());
            assertFalse(grid("SELECT * FROM main.shared").snapshot().isEditable());
        }

        @Test
        void quotedAndReservedWordNamesWork() throws Exception {
            GridModel spaced = grid("SELECT * FROM \"my table\"");
            assertTrue(spaced.snapshot().isEditable());
            edit(spaced, 0, 1, "w2");
            spaced.apply(connection);
            assertEquals("w2", scalar("SELECT \"weird col\" FROM \"my table\""));

            GridModel reserved = grid("SELECT * FROM \"order\"");
            edit(reserved, 0, 1, "g2");
            reserved.apply(connection);
            assertEquals("g2", scalar("SELECT \"group\" FROM \"order\""));
        }

        @Test
        void autoincrementRowInsertedFromTheGridIsEditableAfterwards() throws Exception {
            GridModel grid = grid("SELECT * FROM \"order\"");
            int added = grid.addRow().getFocusRow();
            grid.edit(added, 1, "new");
            grid.apply(connection);

            grid.edit(added, 1, "newer");
            grid.apply(connection);

            assertEquals("newer", scalar("SELECT \"group\" FROM \"order\" WHERE id = 2"));
            assertEquals("2", scalar("SELECT COUNT(*) FROM \"order\""));
        }
    }
}
