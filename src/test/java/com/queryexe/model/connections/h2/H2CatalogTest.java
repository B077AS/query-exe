package com.queryexe.model.connections.h2;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import com.queryexe.model.connections.h2.H2Catalog.ColumnInfo;
import com.queryexe.model.connections.h2.H2Catalog.ForeignKeyInfo;
import com.queryexe.model.connections.h2.H2Catalog.IndexInfo;
import com.queryexe.model.connections.h2.H2Catalog.KeyInfo;

class H2CatalogTest {

    private Connection connection;
    private H2Catalog catalog;

    @BeforeEach
    void fixture() throws SQLException {
        connection = DriverManager.getConnection("jdbc:h2:mem:catalog;DB_CLOSE_DELAY=-1", "sa", "");
        catalog = new H2Catalog(connection);
        execute(connection,
                "DROP ALL OBJECTS",
                "CREATE SCHEMA OTHER",
                "CREATE SCHEMA \"MixedCase\"",
                "CREATE TABLE PUBLIC.T(ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, V VARCHAR(50) NOT NULL DEFAULT 'it''s', "
                        + "P DECIMAL(10,2), TS TIMESTAMP(3), TZ TIMESTAMP(2) WITH TIME ZONE, AR INT ARRAY, E ENUM('a','b'), "
                        + "IV INTERVAL DAY TO SECOND, BN BINARY(4), CH CHAR(3), G INT GENERATED ALWAYS AS (ID * 2), CL CLOB, J JSON, "
                        + "PLAIN VARCHAR, NUM NUMERIC)",
                "CREATE TABLE OTHER.P(A INT, B INT, PRIMARY KEY(A,B))",
                "CREATE TABLE PUBLIC.C(ID INT PRIMARY KEY, A INT, B INT, X INT, Y INT, Z INT, "
                        + "CONSTRAINT FK_AB FOREIGN KEY(A,B) REFERENCES OTHER.P(A,B) ON DELETE CASCADE ON UPDATE SET NULL, "
                        + "CONSTRAINT UQ_XY UNIQUE(X,Y), UNIQUE(Z))",
                "CREATE INDEX IDX_C ON PUBLIC.C(X DESC, Y)",
                "CREATE UNIQUE INDEX UIDX_C ON PUBLIC.C(Y)",
                "CREATE TABLE \"MixedCase\".\"We ird\"(\"Id\" INT PRIMARY KEY, \"Na me\" VARCHAR(5))");
    }

    @AfterEach
    void close() throws SQLException {
        connection.close();
    }

    private static void execute(Connection c, String... statements) throws SQLException {
        try (Statement s = c.createStatement()) {
            for (String statement : statements) {
                s.execute(statement);
            }
        }
    }

    private ColumnInfo column(String name) throws SQLException {
        return catalog.columns("PUBLIC", "T").stream().filter(c -> c.getName().equals(name)).findFirst().orElseThrow();
    }

    // ------------------------------------------------------------------------------------ types

    @Test
    void typesKeepTheirLengthPrecisionAndShape() throws SQLException {
        assertEquals("INTEGER", column("ID").getTypeSql());
        assertEquals("CHARACTER VARYING(50)", column("V").getTypeSql());
        assertEquals("DECIMAL(10, 2)", column("P").getTypeSql());
        assertEquals("TIMESTAMP(3)", column("TS").getTypeSql());
        assertEquals("TIMESTAMP(2) WITH TIME ZONE", column("TZ").getTypeSql());
        assertEquals("INTEGER ARRAY", column("AR").getTypeSql());
        assertEquals("ENUM('a', 'b')", column("E").getTypeSql());
        assertEquals("INTERVAL DAY TO SECOND", column("IV").getTypeSql());
        assertEquals("BINARY(4)", column("BN").getTypeSql());
        assertEquals("CHARACTER(3)", column("CH").getTypeSql());
    }

    @Test
    void defaultsAreNotRepeatedAsParameters() throws SQLException {
        assertEquals("CHARACTER VARYING", column("PLAIN").getTypeSql(), "unbounded VARCHAR must not get a length");
        assertEquals("NUMERIC", column("NUM").getTypeSql(), "default NUMERIC precision must not be spelled out");
        assertEquals("CHARACTER LARGE OBJECT", column("CL").getTypeSql());
        assertEquals("JSON", column("J").getTypeSql());
        assertEquals("TIMESTAMP", catalog.columns("PUBLIC", "T").stream()
                .filter(c -> c.getName().equals("TS")).findFirst().map(c -> "TIMESTAMP").orElseThrow());
    }

    @Test
    void identityDefaultsNullabilityAndGeneratedColumns() throws SQLException {
        assertTrue(column("ID").isIdentity());
        assertEquals("BY DEFAULT", column("ID").getIdentityGeneration());
        assertFalse(column("V").isNullable());
        assertEquals("'it''s'", column("V").getDefaultValue());
        assertTrue(column("G").isGenerated());
        assertEquals("\"ID\" * 2", column("G").getGenerationExpression());
    }

    // ------------------------------------------------------------------------------------ constraints

    @Test
    void primaryKeyComesFirstAndUniqueConstraintsKeepTheirColumns() throws SQLException {
        List<KeyInfo> keys = catalog.keys("PUBLIC", "C");

        assertTrue(keys.get(0).isPrimary());
        assertEquals(List.of("ID"), keys.get(0).getColumns());
        KeyInfo composite = keys.stream().filter(k -> k.getName().equals("UQ_XY")).findFirst().orElseThrow();
        assertEquals(List.of("X", "Y"), composite.getColumns());
        assertEquals(3, keys.size());
    }

    @Test
    void compositeForeignKeyInOtherSchemaIsOneKeyWithAllColumns() throws SQLException {
        List<ForeignKeyInfo> fks = catalog.foreignKeys("PUBLIC", "C");

        assertEquals(1, fks.size());
        ForeignKeyInfo fk = fks.get(0);
        assertEquals("FK_AB", fk.getName());
        assertEquals(List.of("A", "B"), fk.getColumns());
        assertEquals("OTHER", fk.getReferenceSchema());
        assertEquals("P", fk.getReferenceTable());
        assertEquals(List.of("A", "B"), fk.getReferenceColumns());
        assertEquals("CASCADE", fk.getDeleteRule());
        assertEquals("SET NULL", fk.getUpdateRule());
    }

    @Test
    void onlyExplicitIndexesAreListed() throws SQLException {
        List<IndexInfo> indexes = catalog.userIndexes("PUBLIC", "C");

        assertEquals(List.of("IDX_C", "UIDX_C"), indexes.stream().map(IndexInfo::getName).toList());
        IndexInfo idx = indexes.get(0);
        assertFalse(idx.isUnique());
        assertEquals(List.of("X", "Y"), idx.getColumns());
        assertEquals(List.of(true, false), idx.getDescending());
        assertTrue(indexes.get(1).isUnique());
    }

    // ------------------------------------------------------------------------------------ scripts

    @Test
    void mixedCaseSchemaAndSpacedNamesAreFoundAsStored() throws SQLException {
        List<ColumnInfo> columns = catalog.columns("MixedCase", "We ird");

        assertEquals(List.of("Id", "Na me"), columns.stream().map(ColumnInfo::getName).toList());
        String script = catalog.createScript("MixedCase", "We ird");
        assertTrue(script.startsWith("CREATE TABLE \"MixedCase\".\"We ird\" ("), script);
        assertTrue(script.contains("\"Na me\" CHARACTER VARYING(5)"), script);
    }

    @Test
    void generatedNamesAreOmittedAndRealNamesKept() throws SQLException {
        String script = catalog.createScript("PUBLIC", "C");

        assertTrue(script.contains("  PRIMARY KEY (\"ID\")"), script);
        assertTrue(script.contains("CONSTRAINT \"UQ_XY\" UNIQUE (\"X\", \"Y\")"), script);
        assertTrue(script.contains("CONSTRAINT \"FK_AB\" FOREIGN KEY (\"A\", \"B\") REFERENCES \"OTHER\".\"P\" (\"A\", \"B\") ON DELETE CASCADE ON UPDATE SET NULL"), script);
        assertTrue(script.contains("CREATE INDEX \"PUBLIC\".\"IDX_C\" ON \"PUBLIC\".\"C\" (\"X\" DESC, \"Y\");"), script);
        assertFalse(script.contains("_INDEX_"), "indexes H2 creates itself must not be emitted: " + script);
    }

    @Test
    void everyTableReplaysIntoAFreshDatabaseWithTheSameStructure() throws SQLException {
        String[][] tables = {{"OTHER", "P"}, {"PUBLIC", "T"}, {"PUBLIC", "C"}, {"MixedCase", "We ird"}};

        try (Connection fresh = DriverManager.getConnection("jdbc:h2:mem:replay;DB_CLOSE_DELAY=-1", "sa", "")) {
            execute(fresh, "DROP ALL OBJECTS", "CREATE SCHEMA OTHER", "CREATE SCHEMA \"MixedCase\"");
            for (String[] table : tables) {
                for (String statement : catalog.createScript(table[0], table[1]).split(";\\s*\n?")) {
                    if (!statement.isBlank()) {
                        execute(fresh, statement);
                    }
                }
            }

            H2Catalog replayed = new H2Catalog(fresh);
            for (String[] table : tables) {
                assertEquals(catalog.columns(table[0], table[1]), replayed.columns(table[0], table[1]), "columns of " + table[1]);
                List<KeyInfo> originalKeys = catalog.keys(table[0], table[1]);
                assertEquals(originalKeys, replayed.keys(table[0], table[1]).stream()
                        .map(k -> rename(k, originalKeys)).toList(), "keys of " + table[1]);
                assertEquals(catalog.foreignKeys(table[0], table[1]), replayed.foreignKeys(table[0], table[1]), "fks of " + table[1]);
                assertEquals(catalog.userIndexes(table[0], table[1]), replayed.userIndexes(table[0], table[1]), "indexes of " + table[1]);
            }
        }
    }

    /** Unnamed constraints get fresh generated names on replay; compare them by shape. */
    private static KeyInfo rename(KeyInfo replayed, List<KeyInfo> original) {
        return original.stream()
                .filter(k -> k.isPrimary() == replayed.isPrimary() && k.getColumns().equals(replayed.getColumns()))
                .findFirst()
                .map(k -> KeyInfo.builder().name(k.getName()).primary(k.isPrimary()).columns(k.getColumns()).build())
                .orElse(replayed);
    }

    @Test
    void currentSchemaFollowsSetSchema() throws SQLException {
        assertEquals("PUBLIC", catalog.currentSchema());
        execute(connection, "SET SCHEMA OTHER");
        assertEquals("OTHER", catalog.currentSchema());
    }
}
