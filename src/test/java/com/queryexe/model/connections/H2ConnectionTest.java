package com.queryexe.model.connections;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Path;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import com.queryexe.model.data.ColumnData;
import com.queryexe.model.data.ForeignKeyData;
import com.queryexe.service.DatabaseConnection;

class H2ConnectionTest {

    private H2Connection h2;
    private Connection connection;

    private void connect(String url) throws SQLException {
        h2 = new H2Connection("h2-conn-test", "h2", "H2", url, "sa", "", null);
        DatabaseConnection.getInstance().initialize(h2);
        connection = DatabaseConnection.getInstance().getConnection();
    }

    @BeforeEach
    void fixture() throws SQLException {
        connect("jdbc:h2:mem:h2conn;DB_CLOSE_DELAY=-1");
        execute("DROP ALL OBJECTS",
                "CREATE SCHEMA OTHER",
                "CREATE SCHEMA \"MixedCase\"",
                "CREATE TABLE PUBLIC.PARENT(ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(50) NOT NULL UNIQUE, "
                        + "PRICE DECIMAL(10,2), DOUBLED INT GENERATED ALWAYS AS (ID * 2))",
                "CREATE TABLE OTHER.PARENT(ID INT PRIMARY KEY, X INT)",
                "CREATE TABLE PUBLIC.COMP(ID INT PRIMARY KEY, X INT, Y INT, Z INT, UNIQUE(X, Y), UNIQUE(Z))",
                "CREATE TABLE PUBLIC.CPARENT(A INT, B INT, PRIMARY KEY(A,B))",
                "CREATE TABLE PUBLIC.CCHILD(ID INT PRIMARY KEY, A INT, B INT, FOREIGN KEY(A,B) REFERENCES PUBLIC.CPARENT(A,B))",
                "CREATE TABLE \"MixedCase\".\"We ird\"(\"Id\" INT PRIMARY KEY, \"Na me\" VARCHAR(5))",
                "CREATE TABLE PUBLIC.\"my_table\"(ID INT PRIMARY KEY, V INT)",
                "CREATE TABLE PUBLIC.\"myXtable\"(ID INT PRIMARY KEY, V INT, OTHERCOL INT)");
    }

    @AfterEach
    void disconnect() {
        DatabaseConnection.getInstance().close("h2-conn-test");
    }

    private void execute(String... statements) throws SQLException {
        try (Statement s = connection.createStatement()) {
            for (String statement : statements) {
                s.execute(statement);
            }
        }
    }

    private static ColumnData column(List<ColumnData> columns, String name) {
        return columns.stream().filter(c -> c.getColumnName().equals(name)).findFirst().orElseThrow();
    }

    // ------------------------------------------------------------------------------------ names

    @Test
    void mixedCaseSchemaIsListedAndItsTablesAreFound() throws SQLException {
        assertTrue(h2.getDatabases(null).contains("MixedCase"));
        assertEquals(List.of("We ird"), h2.getTablesForDatabase("MixedCase"));
        assertEquals(List.of("Id", "Na me"), h2.getAllTablesAndColumns("MixedCase").get("We ird").stream()
                .map(ColumnData::getColumnName).toList());
    }

    @Test
    void configuredSchemaNameMatchesRegardlessOfCase() {
        assertEquals(List.of("MixedCase"), h2.getDatabases("mixedcase"));
        assertEquals(List.of(), h2.getDatabases("nope"));
    }

    @Test
    void noSchemaMeansTheCurrentOne() throws SQLException {
        assertTrue(h2.getTablesForDatabase(null).contains("PARENT"));
        execute("SET SCHEMA OTHER");
        assertEquals(List.of("PARENT"), h2.getTablesForDatabase(null));
    }

    // ------------------------------------------------------------------------------------ columns

    @Test
    void columnsCarryFullTypesAndKeyFlags() throws SQLException {
        List<ColumnData> columns = h2.getColumnsForTable("PUBLIC", "PARENT");

        assertEquals(List.of("ID", "NAME", "PRICE", "DOUBLED"), columns.stream().map(ColumnData::getColumnName).toList());
        assertTrue(column(columns, "ID").isPrimaryKey());
        assertTrue(column(columns, "ID").isAutoIncrement());
        assertEquals("CHARACTER VARYING(50)", column(columns, "NAME").getDataType());
        assertTrue(column(columns, "NAME").isNotNull());
        assertTrue(column(columns, "NAME").isUnique());
        assertEquals("DECIMAL(10, 2)", column(columns, "PRICE").getDataType());
    }

    @Test
    void compositeUniqueDoesNotMakeEachColumnUniqueAndNoRowIsDuplicated() throws SQLException {
        List<ColumnData> columns = h2.getColumnsForTable("PUBLIC", "COMP");

        assertEquals(List.of("ID", "X", "Y", "Z"), columns.stream().map(ColumnData::getColumnName).toList());
        assertFalse(column(columns, "X").isUnique());
        assertFalse(column(columns, "Y").isUnique());
        assertTrue(column(columns, "Z").isUnique());
        assertNull(column(columns, "X").getUniqueIndexName());
    }

    @Test
    void sameTableNameInTwoSchemasStaysSeparate() throws SQLException {
        assertEquals(4, h2.getColumnsForTable("PUBLIC", "PARENT").size());
        assertEquals(2, h2.getColumnsForTable("OTHER", "PARENT").size());
    }

    // ------------------------------------------------------------------------------------ keys / scripts

    @Test
    void compositeForeignKeyIsOneKeyWithAllColumns() throws SQLException {
        Map<String, ForeignKeyData> fks = h2.extractForeignKeys("PUBLIC", "CCHILD");

        assertEquals(1, fks.size());
        ForeignKeyData fk = fks.values().iterator().next();
        assertEquals(List.of("A", "B"), fk.allLocalColumns());
        assertEquals(List.of("A", "B"), fk.allReferenceColumns());
        assertEquals("PUBLIC", fk.getReferenceSchema());
        assertEquals("CPARENT", fk.getReferenceTable());
    }

    @Test
    void selectScriptIsQualifiedWithItsSchema() {
        assertEquals("SELECT * FROM \"OTHER\".\"PARENT\" LIMIT 100;", h2.generateSelectScript("PARENT", "OTHER", 100));
        assertEquals("SELECT * FROM \"MixedCase\".\"We ird\" LIMIT 5;", h2.generateSelectScript("We ird", "MixedCase", 5));
    }

    @Test
    void insertScriptUsesOnlyTheColumnsOfTheRequestedSchemasTable() {
        String other = h2.generateInsertScript("PARENT", "OTHER");
        assertTrue(other.startsWith("INSERT INTO \"OTHER\".\"PARENT\""), other);
        assertTrue(other.contains("\"X\""), other);
        assertFalse(other.contains("NAME") || other.contains("PRICE"), "columns of PUBLIC.PARENT leaked in: " + other);

        String pub = h2.generateInsertScript("PARENT", "PUBLIC");
        assertTrue(pub.contains("\"NAME\"") && pub.contains("\"PRICE\""), pub);
        assertFalse(pub.contains("\"ID\"") || pub.contains("\"X\"") || pub.contains("DOUBLED"),
                "identity/generated/other-schema columns must be left out: " + pub);
    }

    @Test
    void underscoreInATableNameDoesNotMatchOtherTables() {
        String script = h2.generateInsertScript("my_table", "PUBLIC");
        assertFalse(script.contains("OTHERCOL"), "my_table must not pick up columns of \"myXtable\": " + script);
    }

    @Test
    void createScriptCoversMixedCaseNames() {
        String script = h2.generateCreateScript("We ird", "MixedCase");
        assertTrue(script.startsWith("CREATE TABLE \"MixedCase\".\"We ird\" ("), script);
        assertTrue(script.contains("\"Id\" INTEGER NOT NULL"), script);
    }

    // ------------------------------------------------------------------------------------ DDL generation

    @Test
    void createTableSqlQualifiesTheReferencedSchemaAndKeepsCompositeKeys() {
        ForeignKeyData fk = new ForeignKeyData("FK_X", "A", "CPARENT", "A", "CASCADE", "NO ACTION");
        fk.setReferenceSchema("PUBLIC");
        fk.setLocalColumns(List.of("A", "B"));
        fk.setReferenceColumns(List.of("A", "B"));
        List<ColumnData> columns = List.of(new ColumnData("ID", "INTEGER", true, true, false, false));

        String sql = h2.generateCreateTableSQL("OTHER", "NEWT", columns, List.of(fk));

        assertTrue(sql.contains("FOREIGN KEY (\"A\", \"B\") REFERENCES \"PUBLIC\".\"CPARENT\" (\"A\", \"B\") ON DELETE CASCADE"), sql);
        assertEquals(1, sql.split("ON DELETE").length - 1, "the delete rule must not be written twice: " + sql);
    }

    @Test
    void relaxingNotNullKeepsTheLengthAndReallyMakesTheColumnNullable() throws SQLException {
        List<ColumnData> before = h2.getColumnsForTable("PUBLIC", "PARENT");
        List<ColumnData> after = h2.getColumnsForTable("PUBLIC", "PARENT");
        column(after, "NAME").setNotNull(false);

        String sql = h2.generateAlterTableSQL("PUBLIC", "PARENT", "PARENT", before, after,
                new HashMap<>(), new ArrayList<>(), new HashMap<>());
        assertTrue(sql.contains("CHARACTER VARYING(50)"), "length must survive: " + sql);
        execute(sql.split(";\\s*\n?"));

        ColumnData reread = column(h2.getColumnsForTable("PUBLIC", "PARENT"), "NAME");
        assertFalse(reread.isNotNull(), "NAME must be nullable now");
        assertEquals("CHARACTER VARYING(50)", reread.getDataType());
    }


    @Test
    void alteringAColumnKeepsItsDefault() throws SQLException {
        execute("CREATE TABLE PUBLIC.WITH_DEFAULT(ID INT PRIMARY KEY, V VARCHAR(5) NOT NULL DEFAULT 'x')");
        List<ColumnData> before = h2.getColumnsForTable("PUBLIC", "WITH_DEFAULT");
        List<ColumnData> after = h2.getColumnsForTable("PUBLIC", "WITH_DEFAULT");
        column(after, "V").setNotNull(false);

        String sql = h2.generateAlterTableSQL("PUBLIC", "WITH_DEFAULT", "WITH_DEFAULT", before, after,
                new HashMap<>(), new ArrayList<>(), new HashMap<>());
        execute(sql.split(";\s*\n?"));

        execute("INSERT INTO PUBLIC.WITH_DEFAULT(ID) VALUES (1)");
        try (Statement s = connection.createStatement();
             java.sql.ResultSet rs = s.executeQuery("SELECT V FROM PUBLIC.WITH_DEFAULT")) {
            assertTrue(rs.next());
            assertEquals("x", rs.getString(1), "the DEFAULT must survive an ALTER COLUMN that does not mention it");
        }
    }

    @Test
    void anEditorBuiltColumnWithoutADefaultStillKeepsTheExistingOne() throws SQLException {
        execute("CREATE TABLE PUBLIC.EDITOR_DEFAULT(ID INT PRIMARY KEY, V VARCHAR(5) NOT NULL DEFAULT 'x')");
        List<ColumnData> before = h2.getColumnsForTable("PUBLIC", "EDITOR_DEFAULT");
        // what CreateTableModal produces: new objects built from form fields, with no default
        List<ColumnData> after = List.of(
                new ColumnData("ID", "INTEGER", true, true, false, false),
                new ColumnData("V", "CHARACTER VARYING(5)", false, false, false, false));

        execute(h2.generateAlterTableSQL("PUBLIC", "EDITOR_DEFAULT", "EDITOR_DEFAULT", before, after,
                new HashMap<>(), new ArrayList<>(), new HashMap<>()).split(";\s*\n?"));

        execute("INSERT INTO PUBLIC.EDITOR_DEFAULT(ID) VALUES (1)");
        try (Statement s = connection.createStatement();
             java.sql.ResultSet rs = s.executeQuery("SELECT V FROM PUBLIC.EDITOR_DEFAULT")) {
            assertTrue(rs.next());
            assertEquals("x", rs.getString(1));
        }
    }
    @Test
    void unchangedColumnsProduceNoAlter() throws SQLException {
        List<ColumnData> columns = h2.getColumnsForTable("PUBLIC", "PARENT");
        String sql = h2.generateAlterTableSQL("PUBLIC", "PARENT", "PARENT", columns, h2.getColumnsForTable("PUBLIC", "PARENT"),
                new HashMap<>(), new ArrayList<>(), new HashMap<>());
        assertEquals("", sql.trim());
    }

    // ------------------------------------------------------------------------------------ size

    @Test
    void tableSizeIsReadForFileDatabases(@TempDir Path dir) throws SQLException {
        DatabaseConnection.getInstance().close("h2-conn-test");
        connect("jdbc:h2:file:" + dir.resolve("size").toString().replace("\\", "/"));
        execute("CREATE TABLE BIG(ID INT PRIMARY KEY, V VARCHAR(100))",
                "INSERT INTO BIG SELECT X, REPEAT('x', 100) FROM SYSTEM_RANGE(1, 5000)",
                "CHECKPOINT");

        double size = h2.getTableSize("PUBLIC", "BIG");

        assertTrue(size >= 0, "size lookup must succeed, got " + size);
    }
}
